#!/usr/bin/env python3
"""Copies the generated CRDs into chart/crds and renders chart/templates/clusterrole.yaml from
operator/config/rbac/role.yaml, minus the leases rule (the chart grants it in a namespaced Role)."""
import pathlib
import shutil

import yaml

root = pathlib.Path(__file__).resolve().parent.parent
crds = root / "chart" / "crds"
crds.mkdir(parents=True, exist_ok=True)
for old in crds.glob("*.yaml"):
    old.unlink()
for src in sorted((root / "operator" / "config" / "crd").glob("*.yaml")):
    if src.name != "kustomization.yaml":
        shutil.copy(src, crds / src.name)

role = yaml.safe_load((root / "operator" / "config" / "rbac" / "role.yaml").read_text())
rules = [r for r in role["rules"] if "leases" not in r["resources"]]
body = yaml.safe_dump({"rules": rules}, default_flow_style=False, sort_keys=False)
(root / "chart" / "templates" / "clusterrole.yaml").write_text(
    "# Generated by hack/chart-sync.py from operator/config/rbac/role.yaml; do not edit.\n"
    "apiVersion: rbac.authorization.k8s.io/v1\n"
    "kind: ClusterRole\n"
    "metadata:\n"
    '  name: {{ include "ach-agent.fullname" . }}\n'
    "  labels:\n"
    '    {{- include "ach-agent.labels" . | nindent 4 }}\n' + body
)
